/**
 * Agentic AI:
 * Till now, we have built simple AI systems where:
 * - User asks a question
 * - Model gives a direct answer
 *
 * This works fine for easy tasks like:
 * - Summarizing text
 * - Answering questions
 * - Classifying sentiment
 *
 *
 * But in real production systems, tasks are more complex.
 *
 * Example of complex tasks:
 * - Book a flight
 * - Research latest stock prices and compare them
 * - Read documents, analyze them, and generate a report
 * - Call multiple APIs and combine results
 *
 * A single direct response is not enough.
 *
 *
 * So we use Agentic AI.
*/

/**
 * What is an Agent?
 * An Agent is an AI system that can:
 * 1. Understand a goal
 * 2. Break it into smaller steps
 * 3. Decide what action to take
 * 4. Use tools (APIs, databases, web search, etc.)
 * 5. Observe the result
 * 6. Continue until the goal is achieved
 *
 *
 * Simple Difference:
 * > Normal AI  → Answers questions
 * > Agentic AI → Takes actions to complete tasks
 *
 *
 * Mental Model:
 * > LLM   = Brain
 * > Tools = Hands
 * > Agent = Brain + Hands working step-by-step
 */
