/**
 * Data Transfer Techniques:
 * > Whenever we build websites, there are two main components:
 *   1. Client  → The user's device (browser like Chrome, Edge, etc.)
 *   2. Server  → The machine where website files and data are stored
 *
 * > Data transfer happens between the client and the server.
 *
 * > For example:
 *   - If we want to load an HTML page in the browser (client),
 *   - And that HTML page is stored on the server,
 *   - Then the HTML file is transferred (downloaded) from the server to the
 *     client.
 *
 * > After receiving the HTML file, the browser renders it and displays the
 *   webpage to the user.
 *
 * > Now, we will see how many ways we can transfer data between client and
 *   server:
 *   1. Buffered Response
 *   2. HTTP Streaming
 *   3. Partial Content Response
 *   4. Resumable Uploads
 */
