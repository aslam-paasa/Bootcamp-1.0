/**
 * Linux:
 * > Linux is an open-source kernel, not a complete operating system. 
 * > A kernel is the core software that allows applications to interact
 *   with the hardware. 
 * > The Linux Kernel is written in C language and was developed by 
 *   Linus Torvalds in 1991.
 * 
 * An Operating System (OS) = Kernel + Libraries + Tools + Packages.
*/

/**
 * Linux Distros (Distributions):
 * > Linux comes in different versions called distributions (distros). 
 * > These are categorized based on their usage:
 *   a. Desktop: Ubuntu, Fedora, Linux Mint
 *   b. Server: CentOS, Debian, Red Hat Enterprise Linux
 *   c. Mobile: Android
 *   d. Embedded: Raspberry Pi OS
 * > Linux Kernel Repository: https://github.com/torvalds/linux
*/

