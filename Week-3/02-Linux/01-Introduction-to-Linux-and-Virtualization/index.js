/**
 * Hypervisors (Virtualization):
 * > A Hypervisor is software that allows multiple virtual machines (VMs)
 *   to run on a single physical machine by logically partitioning 
 *   hardware resources.
 * 
 * Types of Hypervisor:
 * 1. Type 1 (Bare Metal):
 *    - Runs directly on the host's hardware.
 *    - Examples: VMware ESXi, Microsoft Hyper-V, KVM
 * 
 * 2. Type 2 (Hosted):
 *    - Runs on top of a conventional operating system.
 *    - Examples: Oracle VirtualBox, VMware Workstation, Parallels Desktop
*/
